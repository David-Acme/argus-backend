struct NumericSetting
{
  const char* key;
  const char* group;
  SettingLevel level{SettingLevel::Advanced};
  SettingApply apply{SettingApply::Restart};
  SettingRange range{};
  const char* fallback;
};

struct ToggleSetting
{
  const char* key;
  const char* group;
  SettingLevel level{SettingLevel::Advanced};
  SettingApply apply{SettingApply::Restart};
  const char* fallback;
};

SettingSpec integer(const NumericSetting& setting)
{
  return {.key = setting.key,
          .group = setting.group,
          .type = SettingType::Integer,
          .level = setting.level,
          .apply = setting.apply,
          .range = setting.range,
          .choices = {},
          .fallback = setting.fallback};
}

SettingSpec decimal(const NumericSetting& setting)
{
  return {.key = setting.key,
          .group = setting.group,
          .type = SettingType::Decimal,
          .level = setting.level,
          .apply = setting.apply,
          .range = setting.range,
          .choices = {},
          .fallback = setting.fallback};
}

SettingSpec toggle(const ToggleSetting& setting)
{
  return {.key = setting.key,
          .group = setting.group,
          .type = SettingType::Toggle,
          .level = setting.level,
          .apply = setting.apply,
          .range = {},
          .choices = {},
          .fallback = setting.fallback};
}

